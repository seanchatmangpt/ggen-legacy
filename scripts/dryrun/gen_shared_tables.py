#!/usr/bin/env python3
"""T-012: emit sharedTables.contract.test.ts with every srve_* table + owning resource (from xaas)."""
import re, sys, os
sys.path.insert(0, os.path.dirname(__file__))
from _common import *
owner = {}
for p in walk(f"{XAAS}/lib/xaas/serv_engine", ".ex"):
    t = open(p).read()
    if "data_layer: AshPostgres" not in t: continue
    for m in re.finditer(r'table\(?\s*"(srve_[a-z_0-9]+)"', t):
        owner.setdefault(m.group(1), rel(p).split("serv_engine/", 1)[1])
mig = set()
for p in walk(f"{XAAS}/priv/repo/migrations", ".exs"):
    mig |= set(re.findall(r"create table\(:(srve_[a-z_0-9]+)", open(p).read()))
tables = sorted(mig | set(owner))
def prisma(t): return "Srve" + "".join(w.capitalize() for w in t[5:].split("_"))
rows = "\n".join(f'  {{ table: "{t}", resource: {("\"" + owner[t] + "\"") if t in owner else "null"} }},' for t in tables)
ts = f'''/**
 * Shared-table tripwire (T-012). GENERATED by scripts/dryrun/gen_shared_tables.py from xaas
 * (lib/xaas/serv_engine table(...) + priv/repo/migrations create table). resource=null means a
 * migration-only table with no AshPostgres resource.
 * Derivation: grep -rhoE 'create table\\(:srve_[a-z_0-9]+' ~/xaas/priv/repo/migrations | sort -u
 */
import * as fs from "fs";
import * as os from "os";
import * as path from "path";

export const EXPECTED_SHARED_TABLES: {{ table: string; resource: string | null }}[] = [
{rows}
];

const XAAS_ROOT = process.env.XAAS_ROOT || path.join(os.homedir(), "xaas");
const schema = fs.readFileSync(path.join(__dirname, "../../../prisma/schema.prisma"), "utf8");

describe("xaas shared srve_* tables", () => {{
  it("census has {len(tables)} unique tables", () => {{
    const names = EXPECTED_SHARED_TABLES.map((e) => e.table);
    expect(new Set(names).size).toBe(names.length);
    expect(names.length).toBe({len(tables)});
  }});

  it("prisma does not model any srve_* table outside the census", () => {{
    const known = new Set(EXPECTED_SHARED_TABLES.map((e) => e.table));
    const modeled = [...schema.matchAll(/@@map\\("(srve_[a-z_0-9]+)"\\)/g)].map((m) => m[1]);
    expect(modeled.filter((t) => !known.has(t))).toEqual([]);
  }});

  it("every xaas migration table has a census entry (loud skip if xaas absent)", () => {{
    const dir = path.join(XAAS_ROOT, "priv/repo/migrations");
    if (!fs.existsSync(dir)) {{
      console.warn(`[xaas-contract] SKIP: ${{dir}} absent`);
      return;
    }}
    const found = new Set<string>();
    for (const f of fs.readdirSync(dir)) {{
      const src = fs.readFileSync(path.join(dir, f), "utf8");
      for (const m of src.matchAll(/create table\\(:(srve_[a-z_0-9]+)/g)) found.add(m[1]);
    }}
    const known = new Set(EXPECTED_SHARED_TABLES.map((e) => e.table));
    expect([...found].filter((t) => !known.has(t))).toEqual([]);
  }});
}});
'''
# Never write into a source tree: the artifact is emitted next to the manifests and adopted into
# onengine-backend/src/xaas-contract/__tests__/ by the srve owners.
out = f"{MAN}/sharedTables.contract.test.ts.txt"
os.makedirs(os.path.dirname(out), exist_ok=True); open(out, "w").write(ts)
print(len(tables), len(owner), len(mig), "->", out)
